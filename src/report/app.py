"""fs-report: drafts three regulatory documents for the case and stores them
in S3 (fs-evidence bucket, reports/<case_id>/):

  1. RBI cyber incident report (to be filed via RBI's reporting platform)
  2. CERT-In incident report
  3. DPDP personal data breach notice

Every draft is clearly marked DRAFT - a human (CISO / DPO) reviews and
submits it. If Bedrock is not configured or fails, template text is used.
"""
import json
import os
from datetime import datetime, timedelta, timezone

import boto3

s3 = boto3.client("s3")
cases_table = boto3.resource("dynamodb").Table(os.environ["CASES_TABLE"])
bedrock = boto3.client("bedrock-runtime")
EVIDENCE_BUCKET = os.environ["EVIDENCE_BUCKET"]
MODEL_ID = os.environ.get("MODEL_ID", "NONE")
IST = timezone(timedelta(hours=5, minutes=30))
ENTITY = "FinShield Lending Pvt. Ltd. (NBFC - digital lending)"
SECTIONS = ["RBI_INCIDENT_REPORT", "CERTIN_INCIDENT_REPORT", "DPDP_BREACH_NOTICE"]


def as_list(v):
    return [str(x) for x in (v or [])]


def facts_for(case, event):
    detected_at = case.get("detected_at") or event.get("detected_at")
    deadline = "[TO BE CONFIRMED]"
    try:
        deadline = (datetime.fromisoformat(detected_at) + timedelta(hours=6)).isoformat(timespec="minutes")
    except (TypeError, ValueError):
        pass
    return {
        "incident_id": case.get("case_id") or event["case_id"],
        "reporting_entity": ENTITY,
        "detected_at": detected_at,
        "reporting_deadline_6h": deadline,
        "contained_at": case.get("contained_at", "[TO BE CONFIRMED]"),
        "account_disabled_at": case.get("disabled_at", "[TO BE CONFIRMED]"),
        "approved_by": case.get("approver", "[TO BE CONFIRMED]"),
        "actor": case.get("actor_id") or event.get("actor_id"),
        "severity": case.get("severity") or event.get("severity"),
        "signals": as_list(case.get("signals") or event.get("signals")),
        "summary": case.get("summary") or event.get("summary"),
        "mitre": as_list(case.get("mitre") or event.get("mitre")),
        "regulation": as_list(case.get("regulation") or event.get("regulation")),
        "documents_involved": str(case.get("docs_involved", event.get("docs_involved", "[TO BE CONFIRMED]"))),
        "destinations": as_list(case.get("destinations") or event.get("destinations")),
        "containment": as_list(case.get("containment")),
        "data_categories": ["Aadhaar copies", "PAN copies", "Photographs", "Address proof"],
        "systems_affected": ["KYC document store (cloud object storage)"],
        "evidence": f"{case.get('evidence_key', '[n/a]')} (SHA-256 {case.get('evidence_hash', '[n/a]')})",
    }


def template_drafts(f):
    common = (
        f"**Incident ID:** {f['incident_id']}  \n"
        f"**Reporting entity:** {f['reporting_entity']}  \n"
        f"**Detected at:** {f['detected_at']}  \n"
        f"**Severity:** {f['severity']}  \n"
        f"**Nature of incident:** Suspected exfiltration of customer KYC documents using a privileged account "
        f"({f['actor']}). Signals: {', '.join(f['signals'])}.  \n"
        f"**Summary:** {f['summary']}  \n"
        f"**Systems affected:** {', '.join(f['systems_affected'])}  \n"
        f"**Data categories:** {', '.join(f['data_categories'])}  \n"
        f"**Approx. documents involved:** {f['documents_involved']}  \n"
        f"**Unauthorized destination(s):** {', '.join(f['destinations']) or 'n/a'}  \n"
        f"**Containment:** {', '.join(f['containment']) or 'n/a'} at {f['contained_at']}; account disabled at "
        f"{f['account_disabled_at']} (approved by {f['approved_by']})  \n"
        f"**MITRE ATT&CK:** {', '.join(f['mitre'])}  \n"
        f"**Evidence:** {f['evidence']}  \n"
    )
    header = "> **DRAFT - for CISO / DPO review before submission. Generated by FinShield AI.**\n\n"
    return {
        "RBI_INCIDENT_REPORT": (
            "# Cyber Incident Report to RBI (DRAFT)\n\n" + header + common +
            f"**Target reporting time (6 hours from detection):** {f['reporting_deadline_6h']}  \n"
            "**Channel:** RBI's designated incident reporting platform  \n"
            "**Customer impact assessment:** [TO BE CONFIRMED]  \n"
            "**Next steps:** forensic review, credential rotation, customer impact analysis.\n"
        ),
        "CERTIN_INCIDENT_REPORT": (
            "# Incident Report to CERT-In (DRAFT)\n\n" + header + common +
            f"**Target reporting time (6 hours from detection):** {f['reporting_deadline_6h']}  \n"
            "**Incident type:** Data breach / unauthorized access to IT systems  \n"
            "**Logs preserved:** Yes (raw logs + hash-chained evidence pack, retained 180 days)  \n"
            "**Point of contact:** [CISO name / phone - TO BE CONFIRMED]\n"
        ),
        "DPDP_BREACH_NOTICE": (
            "# Personal Data Breach Intimation under the DPDP Act (DRAFT)\n\n" + header +
            f"**Data Fiduciary:** {f['reporting_entity']}  \n"
            f"**Incident ID:** {f['incident_id']}  \n"
            f"**When it was detected:** {f['detected_at']}  \n"
            f"**What happened:** {f['summary']}  \n"
            f"**Personal data involved:** {', '.join(f['data_categories'])}  \n"
            f"**Approx. records involved:** {f['documents_involved']}  \n"
            "**Likely consequences for Data Principals:** risk of identity misuse and fraudulent loan applications.  \n"
            f"**Measures taken:** {', '.join(f['containment']) or 'n/a'}; account disabled; evidence preserved.  \n"
            "**Recipients:** Data Protection Board of India and affected Data Principals, as per the DPDP Rules.  \n"
            "**Contact (DPO):** [TO BE CONFIRMED]\n"
        ),
    }


def bedrock_drafts(f):
    prompt = (
        "Using ONLY the facts below, write three short, professional regulatory drafts for an Indian NBFC. "
        "Use markdown. Do not invent facts; write [TO BE CONFIRMED] for anything unknown. Start each draft "
        "with a line '> DRAFT - for CISO / DPO review before submission.' Separate the drafts with these exact "
        "marker lines on their own: === RBI_INCIDENT_REPORT ===, === CERTIN_INCIDENT_REPORT ===, "
        "=== DPDP_BREACH_NOTICE ===\n\nFACTS:\n" + json.dumps(f, indent=2)
    )
    resp = bedrock.converse(
        modelId=MODEL_ID,
        messages=[{"role": "user", "content": [{"text": prompt}]}],
        inferenceConfig={"temperature": 0, "maxTokens": 2500},
    )
    text = resp["output"]["message"]["content"][0]["text"]
    out = {}
    for i, name in enumerate(SECTIONS):
        marker = f"=== {name} ==="
        if marker not in text:
            continue
        part = text.split(marker, 1)[1]
        for nxt in SECTIONS[i + 1:]:
            part = part.split(f"=== {nxt} ===", 1)[0]
        if part.strip():
            out[name] = part.strip() + "\n"
    return out


def lambda_handler(event, context):
    case_id = event["case_id"]
    case = cases_table.get_item(Key={"case_id": case_id}).get("Item", {})
    facts = facts_for(case, event)

    drafts = template_drafts(facts)
    ai_used = False
    if MODEL_ID not in ("", "NONE"):
        try:
            ai = bedrock_drafts(facts)
            drafts.update(ai)           # keep template text for any missing section
            ai_used = bool(ai)
        except Exception as exc:
            print("Bedrock report error, using templates:", repr(exc)[:300])

    file_names = {
        "RBI_INCIDENT_REPORT": "rbi_incident_report.md",
        "CERTIN_INCIDENT_REPORT": "certin_incident_report.md",
        "DPDP_BREACH_NOTICE": "dpdp_breach_notice.md",
    }
    report_keys = {}
    for section, name in file_names.items():
        key = f"reports/{case_id}/{name}"
        s3.put_object(Bucket=EVIDENCE_BUCKET, Key=key, Body=drafts[section].encode("utf-8"),
                      ContentType="text/markdown")
        report_keys[section] = f"s3://{EVIDENCE_BUCKET}/{key}"

    cases_table.update_item(
        Key={"case_id": case_id},
        UpdateExpression="SET report_keys = :k, reporting_deadline = :d, reports_ready = :r, reports_ai_used = :a",
        ExpressionAttributeValues={":k": report_keys, ":d": facts["reporting_deadline_6h"],
                                   ":r": True, ":a": ai_used},
    )
    return {"case_id": case_id, "status": "ACCOUNT_DISABLED", "report_keys": report_keys,
            "reporting_deadline": facts["reporting_deadline_6h"]}
